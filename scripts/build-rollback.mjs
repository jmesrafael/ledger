// Builds supabase/rollback/20261109000000_rollback_settlement_controls.sql from the EXACT text of the migrations production already runs
// (20261107 and 20261108 in supabase/migrations/applied/), so the rollback returns the functions to what they were before 1109.
//   node scripts/build-rollback.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const root = new URL('../supabase/', import.meta.url);
const read = (rel) => readFileSync(new URL(rel, root), 'utf8');

// the full text of "create or replace function public.<name>(" up to its closing "$$;"
function fn(sql, name) {
  const key = `create or replace function public.${name}(`;
  const a = sql.lastIndexOf(key);
  if (a < 0) throw new Error(`${name} not found`);
  const ends = ['\nend $$;', '\n$$;'].map((e) => ({ e, i: sql.indexOf(e, a) })).filter((x) => x.i >= 0).sort((x, y) => x.i - y.i)[0];
  if (!ends) throw new Error(`end of ${name} not found`);
  return sql.slice(a, ends.i + ends.e.length);
}
const m1107 = read('migrations/applied/20261107000000_hwm_bimonthly_settlement.sql');
const m1108 = read('migrations/applied/20261108000000_settlement_workflow_integration.sql');

const out = `-- ROLLBACK of 20261109000000_settlement_controls_backup.sql. Generated by scripts/build-rollback.mjs from the text of 20261107 and 20261108.
-- NOT applied to any database. Read docs/settlement-controls.md ("Rollback and recovery") first.
--
-- WHAT IT DOES: puts the four functions that 1109 replaced back to what production ran before it (admin_close_quarter, admin_settlement_preview,
-- admin_attest_settlement, _export_all), removes everything 1109 added (the settle_guard trigger, the new functions, the settlement_exceptions
-- table, the new settlements columns, the two settings), and reloads the API schema.
-- WHAT IT KEEPS ON PURPOSE: the revokes on the four internal helper functions (_export_all, _account_since, _check_min_withdrawal,
-- _exit_fee_rate). Rolling back must never re-open that exposure.
-- WHEN IT REFUSES: as soon as one settlement or exception has been recorded under 1109. Those rows are the audit trail; dropping their columns
-- or table would destroy it. After that, fix forward (a new migration) instead of rolling back.
-- Nothing else is touched: no ledger row, pool entry, high-water mark, deposit or setting other than the two below.

do $$
begin
  if to_regclass('public.settlement_exceptions') is null then
    raise exception 'nothing to roll back: 20261109 is not applied here. Nothing was changed.';
  end if;
  if exists (select 1 from public.settlement_exceptions)
     or exists (select 1 from public.settlements where recorded_at is not null or covered_from is not null or late or backdated or exception_ids <> '{}') then
    raise exception 'rollback refused: a settlement or an exception was already recorded under 20261109. That audit trail must not be dropped; fix forward instead. Nothing was changed.';
  end if;
end $$;

drop trigger if exists settle_guard on public.pool_equity;
drop function if exists public._settle_guard();

-- the 1109 versions go; the previous versions come back
drop function if exists public.admin_attest_settlement(text, numeric, text, timestamptz, int);
drop function if exists public.admin_approve_settlement_exception(text, text, numeric, text, timestamptz, int);
drop function if exists public.admin_backup_coverage(text);

${fn(m1107, 'admin_attest_settlement')}

${fn(m1108, 'admin_close_quarter')}

${fn(m1108, 'admin_settlement_preview')}

${fn(m1108, '_export_all')}

drop function if exists public._settlement_requirements(numeric, timestamptz, jsonb);
drop function if exists public._settlement_check(numeric);
drop function if exists public._settlement_exception(text, timestamptz, numeric);
drop function if exists public._export_extra();
drop function if exists public._dump_table(text);
drop function if exists public._clock();

drop table public.settlement_exceptions;
alter table public.settlements
  drop column if exists covered_from, drop column if exists covered_to, drop column if exists days_after_period_end, drop column if exists late,
  drop column if exists backdated_days, drop column if exists exception_ids, drop column if exists open_positions_at_settlement,
  drop column if exists recorded_at, drop column if exists backdated;
delete from public.ledger_settings where key in ('settlement_window_days', 'settlement_backdate_minutes');

-- access exactly as 1107 / 1108 left it (plus the helper revokes, which stay)
revoke all on function public._export_all() from public, anon, authenticated;
revoke all on function public.admin_close_quarter(text, numeric, numeric, text, timestamptz, text, boolean),
  public.admin_settlement_preview(text, numeric, timestamptz), public.admin_attest_settlement(text, numeric, text, timestamptz) from public;
grant execute on function public.admin_close_quarter(text, numeric, numeric, text, timestamptz, text, boolean),
  public.admin_settlement_preview(text, numeric, timestamptz), public.admin_attest_settlement(text, numeric, text, timestamptz) to anon, authenticated;

notify pgrst, 'reload schema';
`;
mkdirSync(new URL('rollback/', root), { recursive: true });
writeFileSync(new URL('rollback/20261109000000_rollback_settlement_controls.sql', root), out);
console.log(`wrote supabase/rollback/20261109000000_rollback_settlement_controls.sql (${(out.length / 1024).toFixed(1)} KB)`);
