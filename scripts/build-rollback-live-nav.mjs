// Builds supabase/rollback/20261213000000_rollback_live_nav.sql from the EXACT text of the migrations that defined each replaced function before 20261213,
// so the rollback returns them to what production ran.   node scripts/build-rollback-live-nav.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../supabase/', import.meta.url);
const read = (rel) => readFileSync(new URL(rel, root), 'utf8');

// the full text of "create [or replace] function public.<name>(" up to its closing "$$;" (the last definition in the file)
function fn(sql, name) {
  const keys = [`create or replace function public.${name}(`, `create function public.${name}(`];
  const a = Math.max(...keys.map((k) => sql.lastIndexOf(k)));
  if (a < 0) throw new Error(`${name} not found`);
  const ends = ['\nend $$;', '\n$$;'].map((e) => ({ e, i: sql.indexOf(e, a) })).filter((x) => x.i >= 0).sort((x, y) => x.i - y.i)[0];
  if (!ends) throw new Error(`end of ${name} not found`);
  return sql.slice(a, ends.i + ends.e.length).replace(/^create function/, 'create or replace function');
}
const src = {
  _price_now: 'migrations/applied/20261022000000_ledger.sql',
  _history: 'migrations/applied/20261029000000_fund_returns.sql',
  fund_returns: 'migrations/applied/20261029000000_fund_returns.sql',
  price_history: 'migrations/applied/20261023000000_hide_pool_from_investors.sql',
  pool_summary: 'migrations/applied/20261107000000_hwm_bimonthly_settlement.sql',
  bot_post_wallet_snapshot: 'migrations/20261203000000_closed_trades_auto_pool.sql',
  admin_admit_deposits_tv: 'migrations/20261207000000_true_value_pricing.sql',
};
const bodies = Object.entries(src).map(([name, f]) => fn(read(f), name)).join('\n\n');

